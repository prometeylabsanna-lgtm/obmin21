LEGAL_PAGE_BODIES = {
    'PrivacyPage': PRIVACY_BODY,
    'OfferPage': OFFER_BODY,
    'CookiePage': COOKIE_BODY,
}

LEGAL_TEXT_FIELDS = ('title', 'body', 'seo_title', 'seo_description')


def apply_sentence_replacements(value):
    text = value or ''
    for old, new in SENTENCE_REPLACEMENTS:
        if old and old in text:
            text = text.replace(old, new)
    return text


def apply_legal_replacements(apps, schema_editor=None):
    for model_name in LEGAL_PAGE_BODIES:
        model = apps.get_model('content', model_name)
        for row in model.objects.all():
            updates = {}
            for field_name in LEGAL_TEXT_FIELDS:
                current = getattr(row, field_name, '') or ''
                cleaned = apply_sentence_replacements(current)
                if cleaned != current:
                    updates[field_name] = cleaned
            if updates:
                model.objects.filter(pk=row.pk).update(**updates)

