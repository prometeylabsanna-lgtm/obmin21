def fallback_faq_items():
    return [
        SimpleNamespace(question=question, answer=answer, exchange_safe=True)
        for question, answer in BASE_FAQ
    ]


def public_faq_items(limit=None):
    """Активні видимі питання. У режимі «Лише обмін» без них — базові пʼять."""
    from src.content.models import FaqItem
    from src.core.exchange_mode import is_exchange_only

    items = FaqItem.objects.filter(is_active=True).visible()
    if limit is not None:
        items = items[:limit]
    items = list(items)
    if items or not is_exchange_only():
        return items
    return fallback_faq_items()
