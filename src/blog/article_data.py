def body_text(item):
    chunks = [item['lead']]
    for sec in item['sections']:
        chunks.append(sec['h'])
        chunks.extend(sec.get('p') or [])
        for row in sec.get('list') or []:
            chunks.append(f'- {row}')
    return '\n\n'.join(chunks)


def layout_for(post):
    from django.contrib.staticfiles import finders
    from django.templatetags.static import static

    data = BY_SLUG.get(post.slug)
    if not data:
        words = post.title.split()
        h1a = ' '.join(words[:-2]) if len(words) > 2 else post.title
        h1b = ' '.join(words[-2:]) if len(words) > 2 else ''
        return {
            'h1a': h1a,
            'h1b': h1b,
            'lead': post.excerpt,
            'read': post.reading_label(),
            'sections': [],
            'fig_cap': '',
            'fig_url': '',
            'plain': True,
        }
    fig_name = f"images/articles/{data.get('fig_slug') or post.slug}.jpg"
    fig_url = static(fig_name) if finders.find(fig_name) else post.image_url()
    sections = []
    for i, sec in enumerate(data['sections']):
        sections.append({
            'h': sec['h'],
            'p': sec.get('p') or [],
            'list': sec.get('list') or [],
            'fig': i == 0,
        })
    return {
        'h1a': data['h1a'],
        'h1b': data['h1b'],
        'lead': data['lead'],
        'read': data['read'],
        'sections': sections,
        'fig_cap': data['fig_cap'],
        'fig_url': fig_url,
        'plain': False,
    }
